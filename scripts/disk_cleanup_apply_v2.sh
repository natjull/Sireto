def state(path, rel):
    s = path.lstat()
    kind = ('link' if stat.S_ISLNK(s.st_mode) else 'directory' if stat.S_ISDIR(s.st_mode)
            else 'file' if stat.S_ISREG(s.st_mode) else 'special')
