def foreign_status(data):
    parts = data.split(b'\0')
    kept, i = [], 0
    while i < len(parts) and parts[i]:
        entry = parts[i]
        names = [entry[3:].decode()]
        group = [entry]
        i += 1
        if b'R' in entry[:2] or b'C' in entry[:2]:
            names.append(parts[i].decode())
            group.append(parts[i])
            i += 1
        if not all(name in OWN for name in names):
            kept.extend(group)
    return b'\0'.join(kept) + (b'\0' if kept else b'')

