def scan(row):
    root = Path(row['path'])
    if not root.is_absolute() or not root.is_dir() or root.is_symlink():
        fail('racine absente/non régulière : ' + str(root))
    if str(root.resolve()) != str(root):
        fail('parent symbolique : ' + str(root))
    if not str(root).startswith('/Volumes/CATNAT_DATA/SIRETO') or '.pending.' in str(root):
        fail('racine hors périmètre ou pending : ' + str(root))
    if protected(str(root)):
        fail('une racine A serait concernée : ' + str(root))
    if info(root) != row['scan']['root_identity']:
        fail('racine modifiée : ' + str(root))
    expected = row['scan']
    c_exceptions = {r['path']: r for r in expected['C_exceptions']}
    digest = hashlib.sha256()
    candidates, directories, seen = [], [], set()
    allocated, count = 0, 0

    def add(path, rel):
        nonlocal allocated, count
        entry = state(path, rel)
        kind = entry[1]
        count += 1
        digest.update(json.dumps(entry, separators=(',', ':'), ensure_ascii=False).encode() + b'\n')
        ident = (entry[2], entry[3])
        size = entry[6] * 512 if ident not in seen else 0
        if kind != 'directory':
            seen.add(ident)
        opaque = '.pending.' in path.name and kind == 'directory'
        if opaque:
            size = int(subprocess.check_output(['du', '-sk', str(path)], text=True).split()[0]) * 1024
        allocated += size
        held = protected(str(path)) or str(path) in c_exceptions or '.pending.' in path.name
        if kind == 'special' and not held:
            fail('entrée spéciale non inventoriée : ' + str(path))
        if kind == 'directory':
            directories.append(path)
        elif not held:
            if not inside(str(path), str(root)) or protected(str(path)):
                fail('fichier A/hors racine : ' + str(path))
            candidates.append((path, entry))
        return kind, opaque

    def visit(path, rel):
        kind, opaque = add(path, rel)
        if kind == 'directory' and not opaque:
            for child in sorted(path.iterdir(), key=lambda p: p.name):
                visit(child, child.name if rel == '.' else rel + '/' + child.name)

    if row['scope'] == 'direct_files':
        add(root, '.')
        for child in sorted(root.iterdir(), key=lambda p: p.name):
            if not child.is_dir() or child.is_symlink():
                add(child, child.name)
    else:
        visit(root, '.')
    if digest.hexdigest() != expected['tree_digest'] or count != expected['entries_count']:
        fail('snapshot modifié (noms/inodes/tailles/mtime/liens) : ' + str(root))
    if allocated != expected['observed_allocated_bytes'] or len(candidates) != expected['candidate_files']:
        fail('taille/liste de fichiers modifiée : ' + str(root))
    if row['scope'] == 'recursive':
        actual = int(subprocess.check_output(['du', '-sk', str(root)], text=True).split()[0]) * 1024
        if actual != expected['observed_allocated_bytes']:
            fail('du -sk différent du snapshot : ' + str(root))
    return candidates, directories

