# Les buckets parents passent avant leurs sous-unités : pas de rmtree de conteneur mixte.
removed = 0
for row in sorted(rows, key=lambda r: (len(Path(r['path']).parts), r['path'])):
    candidates, directories = scan(row)
    for path, expected in candidates:
        if protected(str(path)) or '.pending.' in str(path):
            fail('A/pending protégé : ' + str(path))
        if state(path, expected[0]) != expected:
            fail('fichier remplacé/modifié pendant application : ' + str(path))
        parent = str(path.parent.resolve())
        if not inside(parent, row['path']) or protected(parent):
            fail('parent symbolique déplacé/hors racine/A : ' + str(path))
        # Unlink uniquement : ne suit jamais les liens symboliques.
        path.unlink()
        ident = (expected[2], expected[3])
        REMOVED_LINKS[ident] = REMOVED_LINKS.get(ident, 0) + 1
        removed += 1
    if row['scope'] == 'recursive':
        for directory in reversed(directories):
            if namespace_protected(str(directory)) or '.pending.' in str(directory):
                continue
            if str(directory) in {r['path'] for r in row['scan']['C_exceptions']}:
                continue
            try:
                # rmdir échoue si une exception, un lien ou un nouveau fichier subsiste.
                directory.rmdir()
            except OSError as exc:
                if exc.errno not in (39, 66):
                    raise
print('Fichiers/liens B supprimés :', removed, '; A, C et pending conservés.')
